import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    kotlin("jvm") version "2.0.21"
}

// ---------------------------------------------------------------------------------------------
// TapOut Guardian build.
//
// This is a plain Gradle + Kotlin build that drives the Android command line tools directly
// (aapt2 -> kotlinc -> dx -> zipalign -> apksigner) instead of the Android Gradle Plugin.
// See README.md ("Why not AGP/Compose?") for the reason. Everything Android-specific that
// needs the framework lives in `com.tapoutguardian.android`/`ui`; the state machine, planner
// and SQL layer in `com.tapoutguardian.core` are pure Kotlin and are unit tested on the JVM.
// ---------------------------------------------------------------------------------------------

val sdkDir: String? = System.getenv("ANDROID_HOME") ?: System.getenv("ANDROID_SDK_ROOT")
    ?: rootProject.file("local.properties").takeIf { it.exists() }?.readLines()
        ?.firstOrNull { it.startsWith("sdk.dir=") }?.substringAfter("=")
val androidJar: File = (System.getenv("ANDROID_JAR")?.let(::File)
    ?: File("$sdkDir/platforms/android-34/android.jar"))
val toolsDir: String = System.getenv("ANDROID_BUILD_TOOLS") ?: "/usr/lib/android-sdk/build-tools/debian"

repositories { mavenCentral() }

dependencies {
    compileOnly(files(androidJar))
    testImplementation("junit:junit:4.13.2")
    testImplementation("org.xerial:sqlite-jdbc:3.46.1.3")
}

java { sourceCompatibility = JavaVersion.VERSION_1_8; targetCompatibility = JavaVersion.VERSION_1_8 }
tasks.withType<JavaCompile>().configureEach { options.release.set(8); options.compilerArgs.add("-Xlint:-options") }

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_1_8)
        // dx cannot translate invokedynamic, so compile lambdas / SAM / string concat the classic way.
        freeCompilerArgs.addAll("-Xlambdas=class", "-Xsam-conversions=class", "-Xstring-concat=inline")
    }
}

val gen = layout.buildDirectory.dir("gen")
sourceSets.main { java.srcDir(gen) }

val aapt2Compile by tasks.registering(Exec::class) {
    val out = layout.buildDirectory.file("aapt/res.zip")
    inputs.dir("src/main/res")
    outputs.file(out)
    doFirst { out.get().asFile.parentFile.mkdirs() }
    commandLine("$toolsDir/aapt2", "compile", "--dir", "src/main/res", "-o", out.get().asFile.path)
}

fun aapt2LinkTask(name: String, debuggable: Boolean) = tasks.register<Exec>(name) {
    dependsOn(aapt2Compile)
    val out = layout.buildDirectory.file("aapt/base-${if (debuggable) "debug" else "release"}.apk")
    inputs.file("src/main/AndroidManifest.xml")
    inputs.file(layout.buildDirectory.file("aapt/res.zip"))
    outputs.file(out)
    if (debuggable) outputs.dir(gen)   // R.java is generated once, by the debug link
    doFirst { gen.get().asFile.mkdirs() }
    val args = mutableListOf(
        "$toolsDir/aapt2", "link", "-o", out.get().asFile.path, "-I", androidJar.path,
        "--manifest", "src/main/AndroidManifest.xml",
        "--min-sdk-version", "26", "--target-sdk-version", "34",
        "--version-code", "1", "--version-name", "1.0.0",
        "--auto-add-overlay", layout.buildDirectory.file("aapt/res.zip").get().asFile.path,
    )
    if (debuggable) args += listOf("--debug-mode", "--java", gen.get().asFile.path)
    commandLine(args)
}

val aapt2LinkDebug = aapt2LinkTask("aapt2LinkDebug", true)
val aapt2LinkRelease = aapt2LinkTask("aapt2LinkRelease", false)

// R.java is generated by the (debug) link step; the release link regenerates an identical one.
tasks.named("compileKotlin") { dependsOn(aapt2LinkDebug) }
tasks.named("compileJava") { dependsOn(aapt2LinkDebug) }

// dx chokes on multi-release/module-info entries in kotlin-stdlib, so unpack only the real classes.
val stdlibClasses by tasks.registering(Copy::class) {
    from(provider { configurations.runtimeClasspath.get().files.filter { it.name.startsWith("kotlin-stdlib") || it.name.startsWith("annotations") }.map { zipTree(it) } })
    exclude("META-INF/**", "module-info.class")
    into(layout.buildDirectory.dir("stdlib-classes"))
}

val dex by tasks.registering(Exec::class) {
    dependsOn("classes", stdlibClasses)
    val out = layout.buildDirectory.dir("dex")
    inputs.files(sourceSets.main.map { it.output.classesDirs }, stdlibClasses)
    outputs.dir(out)
    doFirst {
        out.get().asFile.deleteRecursively(); out.get().asFile.mkdirs()
        val inputs = mutableListOf<String>()
        inputs += layout.buildDirectory.dir("classes/kotlin/main").get().asFile.path
        inputs += layout.buildDirectory.dir("classes/java/main").get().asFile.path
        inputs += layout.buildDirectory.dir("stdlib-classes").get().asFile.path
        commandLine(listOf("$toolsDir/dx", "--dex", "--min-sdk-version=26", "--output=${out.get().asFile.path}/classes.dex") + inputs)
    }
    commandLine("true")
}

fun packageTask(variant: String, link: TaskProvider<Exec>) = tasks.register<Exec>("assemble${variant.replaceFirstChar { it.uppercase() }}Apk") {
    group = "build"
    description = "Builds, aligns and signs the $variant APK"
    dependsOn(dex, link)
    val outDir = layout.buildDirectory.dir("outputs/apk/$variant")
    inputs.files(dex, link, "scripts/package-apk.sh")
    outputs.dir(outDir)
    commandLine(
        "bash", "scripts/package-apk.sh", variant,
        layout.buildDirectory.file("aapt/base-$variant.apk").get().asFile.path,
        layout.buildDirectory.file("dex/classes.dex").get().asFile.path,
        outDir.get().asFile.path, toolsDir,
    )
}
packageTask("debug", aapt2LinkDebug)
packageTask("release", aapt2LinkRelease)

tasks.register("assembleAll") { dependsOn("assembleDebugApk", "assembleReleaseApk") }

// Copies the signed APKs to dist/ for easy hand-off.
tasks.register<Copy>("dist") {
    dependsOn("assembleAll")
    from(layout.buildDirectory.dir("outputs/apk/debug")) { include("*.apk") }
    from(layout.buildDirectory.dir("outputs/apk/release")) { include("*.apk") }
    into("dist")
}

tasks.test {
    useJUnit()
    testLogging { events("passed", "failed", "skipped"); showStandardStreams = false; exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL }
}
